package com.logicBuilding;

public class SwapTwoNumbersUsingThirdVariable {

	public static void main(String[] args) {
		int a =10;
		int b=20;
		System.out.println("a is : "+a);
		System.out.println("b is : "+b);
		int c;
		c=a;
		a=b;
		b=c;
		System.out.println("a is : "+a);
		System.out.println("b is : "+b);

	}

}
